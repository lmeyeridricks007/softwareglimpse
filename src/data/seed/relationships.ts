function crmCompeteMesh(): RelInput[] {
  const crm = softwareSeed
    .filter((s) => s.primaryCategorySlug === "crm")
    .map((s) => s.slug)
    .sort();
  const edges: RelInput[] = [];
  for (let i = 0; i < crm.length; i += 1) {
    for (let j = i + 1; j < crm.length; j += 1) {
      const a = crm[i]!;
      const b = crm[j]!;
      edges.push(
        edge(a, b, "competes-with", strengthForCrmPair(a, b), "crm-peer-comparison"),
      );
    }
  }
  return edges;
}

