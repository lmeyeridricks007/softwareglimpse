function sanitizePeerSlugLists(products: SoftwareInput[]): SoftwareInput[] {
  const slugs = new Set(products.map((product) => product.slug));
  const keep = (productSlug: string, list: string[] | undefined) =>
    [
      ...new Set(
        (list ?? []).filter((slug) => slugs.has(slug) && slug !== productSlug),
      ),
    ];
  return products.map((product) => ({
    ...product,
    competitorSlugs: keep(product.slug, product.competitorSlugs),
    alternativeSlugs: keep(product.slug, product.alternativeSlugs),
    comparableSlugs: keep(product.slug, product.comparableSlugs),
  }));
}

function soft(
  input: SoftwareInput & { slug: string; name: string; id: string },
): SoftwareInput {
  const partnerUrl = getPartnerAffiliateUrl(input.slug);
  const scenarioTags = SOFTWARE_SCENARIO_USE_CASE_TAGS[input.slug] ?? [];
  const useCaseSlugs = [
    ...new Set([...(input.useCaseSlugs ?? []), ...scenarioTags]),
  ];
  const metadata = {
    ...publishedMeta,
    ...(input.metadata ?? {}),
  };
  const isPublished = metadata.status === "published";
  return {
    ...input,
    useCaseSlugs,
    metadata,
    seo: {
      title: input.name,
      description: `${input.name} software profile on SoftwareGlimpse.`,
      indexable: isPublished,
      canonicalPath: `/software/${input.slug}/`,
    },
    affiliate: partnerUrl
      ? {
          enabled: true,
          network: "other",
          trackingUrl: partnerUrl,
          disclosureRequired: true,
          programmeId: `prog-${input.slug}`,
          program: `${input.name} Affiliate`,
        }
      : {
          enabled: false,
          network: "none",
          disclosureRequired: true,
        },
  };
}
