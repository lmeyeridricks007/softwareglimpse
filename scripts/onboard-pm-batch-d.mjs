#!/usr/bin/env node
import {
  configurePmRuntime,
  runPmBatch,
  weightedScore,
  ROOT,
} from "./lib/pm-onboard-runtime.mjs";
import { PRODUCTS, COMPARISON_PAIRS } from "./lib/pm-batch-d-products.mjs";

configurePmRuntime({
  verifiedAt: "2026-08-17T21:00:00.000Z",
  publishedAt: "2026-08-17T00:00:00.000Z",
  batchLabel: "Project-management Batch-D",
  jobTag: "project-management-batch-d",
  relatedGuidePaths: [
    "/categories/project-management/",
    "/best/project-management-software/",
  ],
});

function main() {
  for (const p of PRODUCTS) {
    console.log(`  - ${p.slug} overall=${weightedScore(p.scores)} cluster=${p.jobCluster}`);
  }
  runPmBatch({
    products: PRODUCTS,
    pairs: COMPARISON_PAIRS,
    seedSnippetFile: "_pm-batch-d-seed-snippet.ts",
    comparisonSpecFile: "_pm-batch-d-comparisons.json",
    videoSpecFile: "_pm-batch-d-official-videos.json",
    seedHeader: `// Auto-generated by scripts/onboard-pm-batch-d.mjs
// Batch D: basecamp, todoist, microsoft-project.`,
  });
  console.log(`Root: ${ROOT}`);
}
main();
