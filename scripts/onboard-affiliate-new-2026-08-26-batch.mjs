import {
  configureCsRuntime,
  runCsBatch,
} from "./lib/cs-onboard-runtime.mjs";
import {
  configureAiRuntime,
  runAiBatch,
  weightedScore,
  ROOT,
} from "./lib/ai-onboard-runtime.mjs";
import {
  COMETCHAT_PRODUCT,
  COMETCHAT_COMPARISON_PAIRS,
} from "./lib/affiliate-new-cometchat-product.mjs";
import {
  TURBOTIC_PRODUCT,
  TURBOTIC_COMPARISON_PAIRS,
} from "./lib/affiliate-new-turbotic-product.mjs";

const VERIFIED_AT = "2026-08-26T12:00:00.000Z";
const PUBLISHED_AT = "2026-08-26T00:00:00.000Z";

configureCsRuntime({
  verifiedAt: VERIFIED_AT,
  publishedAt: PUBLISHED_AT,
  batchLabel: "Affiliate new CometChat 2026-08-26",
  jobTag: "affiliate-new-cometchat",
  relatedGuidePaths: [
    "/categories/customer-service/live-chat/",
    "/best/live-chat-software/",
    "/use-cases/live-chat-support/",
  ],
});

