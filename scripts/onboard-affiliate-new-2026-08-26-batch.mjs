    products: [TURBOTIC_PRODUCT],
    pairs: TURBOTIC_COMPARISON_PAIRS,
    seedSnippetFile: "_affiliate-new-turbotic-seed-snippet.ts",
    comparisonSpecFile: "_affiliate-new-turbotic-comparisons.json",
    seedHeader: `// Auto-generated by scripts/onboard-affiliate-new-2026-08-26-batch.mjs
// Append via: node scripts/patch-software-seed-affiliate-new-2026-08-26.mjs`,
