  console.log("\nNext:");
  console.log("  node scripts/patch-software-seed-affiliate-new-2026-08-26.mjs");
  console.log("  node scripts/append-affiliate-new-2026-08-26-comparisons.mjs");
  console.log("  node scripts/source-affiliate-new-2026-08-26-media.mjs");
  console.log("  node scripts/generate-affiliate-new-2026-08-26-lettermarks.mjs");
