import {
  configureEcomRuntime,
  runEcomBatch,
  weightedScore,
  ROOT,
} from "./lib/ecom-onboard-runtime.mjs";
import {
  PRODUCTS,
  COMPARISON_PAIRS,
} from "./lib/ecom-priority1-products.mjs";

configureEcomRuntime({
  verifiedAt: "2026-08-18T14:00:00.000Z",
  publishedAt: "2026-08-18T00:00:00.000Z",
  batchLabel: "Ecommerce Priority-1",
  jobTag: "ecommerce-priority1",
  relatedGuidePaths: [
    "/categories/ecommerce/",
    "/best/ecommerce-software/",
  ],
});

function main() {
  console.log("Ecommerce Priority-1 products:");
  for (const p of PRODUCTS) {
    console.log(
      `  - ${p.slug} overall=${weightedScore(p.scores)} role=${p.membershipRole} cluster=${p.jobCluster}`,
    );
  }
  runEcomBatch({
    products: PRODUCTS,
    pairs: COMPARISON_PAIRS,
    seedSnippetFile: "_ecommerce-priority1-seed-snippet.ts",
    comparisonSpecFile: "_ecommerce-priority1-comparisons.json",
    videoSpecFile: "_ecommerce-priority1-official-videos.json",
    seedHeader: `// Auto-generated by scripts/onboard-ecommerce-priority1-batch.mjs
// Append into src/data/seed/software.ts via:
//   node scripts/patch-software-seed-ecommerce-priority1.mjs
// Ecommerce Priority-1: magento, wix, squarespace.`,
  });

  console.log("\nNext:");
  console.log("  1. node scripts/patch-software-seed-ecommerce-priority1.mjs");
  console.log("  2. node scripts/fetch-brand-logos.mjs magento wix squarespace");
  console.log("  3. Wire approvedEcomPair entries from scripts/_ecommerce-priority1-comparisons.json");
  console.log("  4. Update best.ts ecommerce page (website-builder award + Magento landscape)");
  console.log("  5. No WordPress auto-publish");
  console.log(`\nRoot: ${ROOT}`);
}

main();
